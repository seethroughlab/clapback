@browse_router.get("/browse/hash/{prefix}", response_model=HashResolution)
@limiter.limit(settings.lookup_rate_limit)
async def resolve_prefix(request: Request, prefix: str, db: DbSession) -> HashResolution:
    """A hash from its prefix — the twelve hex characters the map carries per point.

    Twelve is 48 bits; the corpus is tens of thousands of rows, so a collision is
    a curiosity rather than a risk, and an ambiguous prefix is refused rather than
    guessed at. Returns the most-contributed row for the hash and the recording it
    resolves to, if anyone has claimed one.
    """
    prefix = prefix.lower()
    if len(prefix) < 12 or len(prefix) > 64 or not HEX_RE.match(prefix):
        raise HTTPException(status_code=422, detail="prefix must be 12 to 64 hex characters")
    rows = (
        await db.execute(
            select(Embedding.fingerprint_hash, Embedding.pipeline_version, Embedding.contributor_count)
            .where(Embedding.fingerprint_hash.like(prefix + "%"))
            .order_by(Embedding.contributor_count.desc(), Embedding.pipeline_version)
            .limit(3)
        )
    ).all()
    if not rows:
        raise HTTPException(status_code=404, detail="no recording with that prefix")
    hashes = {r.fingerprint_hash for r in rows}
    if len(hashes) > 1:
        raise HTTPException(status_code=409, detail="prefix is ambiguous; send more of it")
    h, pipeline, count = rows[0]
    recording = (await _recordings_for(db, [h])).get(h)
    return HashResolution(
        fingerprint_hash=h,
        pipeline_version=pipeline,
        contributor_count=int(count or 1),
        recording_mbid=recording[0] if recording else None,
        recording_claims=recording[1] if recording else 0,
    )
